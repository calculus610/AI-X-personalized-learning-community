type QuizQuestionDefinition = {
  id: string
  knowledgePointId: string
  knowledgePointLabel: string
  prompt: string
  options: Array<{ id: string; text: string }>
  correctOptionId: string
  explanation: string
}

function question(
  knowledgePointId: string,
  knowledgePointLabel: string,
  prompt: string,
  correct: string,
  distractors: [string, string, string],
  explanation: string,
): QuizQuestionDefinition {
  return {
    id: `quiz-${knowledgePointId}`,
    knowledgePointId,
    knowledgePointLabel,
    prompt,
    options: [
      { id: "A", text: correct },
      { id: "B", text: distractors[0] },
      { id: "C", text: distractors[1] },
      { id: "D", text: distractors[2] },
    ],
    correctOptionId: "A",
    explanation,
  }
}

