const questionById = new Map(adaptiveQuizBank.map((item) => [item.id, item]))

export function getQuizDefinitions(knowledgePointIds: string[]) {
  const selected = new Set(knowledgePointIds)
  return adaptiveQuizBank.filter((item) => selected.has(item.knowledgePointId)).slice(0, 3)
}

export function getQuizDefinition(questionId: string) {
  return questionById.get(questionId) ?? null
}
